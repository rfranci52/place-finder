#!/usr/bin/env python3
"""Rebuilds the ZIP code table at the end of frontend/api/search.py from the loaded places.

NYC GeoSearch has no ZIP code index, so a location typed as a bare ZIP code is answered from
this table. Each ZIP code's center is the median position of the loaded places that carry it.
A ZIP code is kept when at least MIN_PLACES places carry it and its center falls inside the
borough its first three digits imply (100-102 Manhattan, 103 Staten Island, 104 the Bronx,
112 Brooklyn, 110, 111, 113, 114 and 116 Queens), which drops ZIP codes known only from a few
misfiled addresses.

Reads with the app's own read-only role (PLACES_DB_URL, from the process environment or the env
file). Run it after each monthly refresh:

    python scripts/build_zip_centers.py            # rewrite the table
    python scripts/build_zip_centers.py --dry-run  # print what would change, write nothing
"""
from __future__ import annotations

import argparse
import os
import re
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from setup_db import DEFAULT_ENV_FILE, URL_VARIABLE, read_env  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]
SEARCH_FILE = REPO_ROOT / "frontend" / "api" / "search.py"
MIN_PLACES = 20
BEGIN = "# BEGIN ZIP CENTERS (generated by scripts/build_zip_centers.py; do not edit by hand)"
END = "# END ZIP CENTERS"

PREFIX_BOROUGHS = {
    "100": "Manhattan", "101": "Manhattan", "102": "Manhattan", "103": "Staten Island", "104": "Bronx",
    "112": "Brooklyn", "110": "Queens", "111": "Queens", "113": "Queens", "114": "Queens", "116": "Queens",
}

POINTS_SQL = """
select left(postcode, 5), st_y(geog::geometry), st_x(geog::geometry)
from places.places
where postcode ~ '^[0-9]{5}'
"""
BOROUGH_SQL = """
select b.boroname from places.boroughs b
where st_intersects(b.geom, st_setsrid(st_makepoint(%s, %s), 4326))
order by b.borocode limit 1
"""
RELEASE_SQL = "select m.value from places.meta m where m.key = 'release'"


def expected_borough(code: str) -> str | None:
    return PREFIX_BOROUGHS.get(code[:3])


def centers(points: dict[str, list[tuple[float, float]]], borough_of) -> dict[str, tuple[float, float, str]]:
    """{zip: (lat, lng, borough)} for the ZIP codes that pass both checks."""
    kept = {}
    for code, pts in sorted(points.items()):
        if len(pts) < MIN_PLACES or not re.fullmatch(r"[0-9]{5}", code):
            continue
        lat = statistics.median(p[0] for p in pts)
        lng = statistics.median(p[1] for p in pts)
        borough = borough_of(lat, lng)
        if borough is not None and borough == expected_borough(code):
            kept[code] = (lat, lng, borough)
    return kept


def render(kept: dict[str, tuple[float, float, str]], release: str) -> str:
    lines = [BEGIN, f"# Data release {release}: {len(kept)} ZIP codes, each kept with at least {MIN_PLACES} places.",
             'ZIP_CENTERS_TEXT = """']
    lines += [f"{code} {lat:.5f} {lng:.5f} {borough}" for code, (lat, lng, borough) in sorted(kept.items())]
    lines += ['"""', "ZIP_CENTERS = {", "    code: (float(lat), float(lng), \" \".join(borough))",
              "    for code, lat, lng, *borough in (line.split() for line in ZIP_CENTERS_TEXT.splitlines() if line.strip())",
              "}", END]
    return "\n".join(lines)


def replace_block(source: str, block: str) -> str:
    """The source with the generated block replaced, or appended at the end when it is not there yet."""
    start, stop = source.find(BEGIN), source.find(END)
    if start == -1 and stop == -1:
        return source.rstrip("\n") + "\n\n\n" + block + "\n"
    if start == -1 or stop == -1 or stop < start:
        raise SystemExit("build_zip_centers: the ZIP block markers in search.py are damaged; fix them by hand")
    return source[:start] + block + source[stop + len(END):]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--env-file", type=Path, default=Path(os.environ.get("PLACES_ENV_FILE") or DEFAULT_ENV_FILE))
    parser.add_argument("--dry-run", action="store_true", help="print the counts and write nothing")
    args = parser.parse_args()
    url = os.environ.get(URL_VARIABLE) or read_env(args.env_file).get(URL_VARIABLE, "")
    if not url:
        raise SystemExit(f"build_zip_centers: {URL_VARIABLE} is not set in the environment or in {args.env_file.name}")

    import psycopg

    points: dict[str, list[tuple[float, float]]] = {}
    with psycopg.connect(url, prepare_threshold=None) as conn:
        for code, lat, lng in conn.execute(POINTS_SQL):
            points.setdefault(code, []).append((float(lat), float(lng)))

        def borough_of(lat, lng):
            row = conn.execute(BOROUGH_SQL, (lng, lat)).fetchone()
            return row[0] if row else None

        kept = centers(points, borough_of)
        release = (conn.execute(RELEASE_SQL).fetchone() or ["unknown"])[0]

    by_borough = {}
    for _, _, borough in kept.values():
        by_borough[borough] = by_borough.get(borough, 0) + 1
    print(f"build_zip_centers: {len(kept)} ZIP codes kept of {len(points)} seen; {by_borough}")
    if args.dry_run:
        return
    source = SEARCH_FILE.read_text(encoding="utf-8")
    SEARCH_FILE.write_text(replace_block(source, render(kept, release)), encoding="utf-8")
    print(f"build_zip_centers: wrote {SEARCH_FILE.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
